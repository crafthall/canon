#!/usr/bin/env node
// Builds the runner of the standalone Claude Code plugin crafthall-canon (ADR-0002): bundles
// src/plugin-runner.ts with the `canon` CLI (src/cli.ts) and the whole core into one ESM file with no dependencies,
// plugin/scripts/hub-core.mjs (Node >= 20; the plugin needs no npm install, no checkout of this repository and no network).
// The launcher plugin/scripts/hub.mjs (hand-written, three lines) imports it and calls pluginMain: a separate file, so
// the CLI's own "run when invoked" check (argv[1] = the module file) is false inside the bundle.
// It also copies the page template (template/ → plugin/template/), which `canon new` and `canon init` use in a repository
// without its own docs/product-hub/_template/: the bundle finds it next to scripts/ as the source tree does next to src/.
// A copy, not a link: Claude Code drops symbolic links that point out of an installed plugin's folder.
// Both are committed; tests/plugin.test.ts builds them again and fails when the committed copy is stale.
//   node scripts/build-plugin.mjs              (npm run build:plugin)
//   node scripts/build-plugin.mjs --out <dir>  (build a plugin's scripts/ and template/ under <dir>)
import { build } from 'esbuild';
import { cpSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const LIB = dirname(dirname(fileURLToPath(import.meta.url)));
export const PLUGIN = join(LIB, 'plugin');
export const PLUGIN_BUNDLE = join(PLUGIN, 'scripts', 'hub-core.mjs');
export const TEMPLATE = join(LIB, 'template');
export const PLUGIN_TEMPLATE = join(PLUGIN, 'template');

const BANNER = [
  '// GENERATED by scripts/build-plugin.mjs from src – do not edit; run npm run build:plugin.',
  '// Crafthall Canon core and `canon` CLI for the Claude Code plugin crafthall-canon. No dependencies, no network.',
  '/* eslint-disable */',
].join('\n');

/** Bundles the runner to `outfile` (default the plugin's committed copy); returns the esbuild metafile. */
export async function buildPluginBundle(outfile = PLUGIN_BUNDLE) {
  mkdirSync(dirname(outfile), { recursive: true });
  const r = await build({
    entryPoints: [join(LIB, 'src', 'plugin-runner.ts')],
    outfile,
    bundle: true,
    platform: 'node',
    target: 'node20',
    format: 'esm',
    minify: false,
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: BANNER },
    metafile: true,
    absWorkingDir: LIB,
  });
  return r.metafile;
}

/** Builds the generated part of a plugin folder under `dir` (default the plugin): scripts/hub-core.mjs and template/. */
export async function buildPlugin(dir = PLUGIN) {
  const meta = await buildPluginBundle(join(dir, 'scripts', 'hub-core.mjs'));
  const template = join(dir, 'template');
  rmSync(template, { recursive: true, force: true });
  cpSync(TEMPLATE, template, { recursive: true });
  return meta;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--out');
  const out = i > 0 ? resolve(process.argv[i + 1]) : PLUGIN;
  const meta = await buildPlugin(out);
  console.log(`canon plugin – bundled ${Object.keys(meta.inputs).length} files into ${join(out, 'scripts', 'hub-core.mjs')} and copied the template to ${join(out, 'template')}`);
}
